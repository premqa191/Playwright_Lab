import pytest
from playwright.sync_api import sync_playwright, expect

def test_web_first_assertions():
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page()

        # ??????? ??????? ?????? ???????
        page.goto('https://the-internet.herokuapp.com/dynamic_loading/1')
        start_btn = page.get_by_role('button', name='Start')
        finish_text = page.locator('#finish h4')

        # 1. ?????????? ?????? ???????? ???????????? (Hidden check)
        expect(finish_text).not_to_be_visible()

        # 2. ???? ?????? ????? (??????? ???? ???????????????)
        start_btn.click()

        # 3. Web-First Assertion: ??????? ??????? 'Hello World!' ???????? ???? ???-?????? ?????????
        expect(finish_text).to_be_visible(timeout=10000)
        expect(finish_text).to_have_text('Hello World!')

        browser.close()
